"""Download Google Material Symbols (Outlined, weight 400, 24px, Apache-2.0) and generate
crates/omni-shell/src/icons_data.rs (SVG path data, viewBox "0 -960 960 960").
Usage: python3 tools/gen_icons.py"""
import re, sys, urllib.request
BASE = "https://raw.githubusercontent.com/google/material-design-icons/master/symbols/web/%s/materialsymbolsoutlined/%s_24px.svg"
# our icon name -> candidate Material Symbols names (first that exists wins)
ICONS = {
 "note_add": ["note_add"], "folder_open": ["folder_open"], "save": ["save"], "save_as": ["save_as"], "history": ["history"],
 "undo": ["undo"], "redo": ["redo"], "content_cut": ["content_cut"], "content_copy": ["content_copy"], "content_paste": ["content_paste"],
 "format_paint": ["format_paint"], "format_bold": ["format_bold"], "format_italic": ["format_italic"], "format_underlined": ["format_underlined"],
 "format_align_left": ["format_align_left"], "format_align_center": ["format_align_center"], "format_align_right": ["format_align_right"],
 "format_align_justify": ["format_align_justify"], "format_quote": ["format_quote"], "code": ["code"],
 "uppercase": ["match_case", "text_fields"], "lowercase": ["text_fields"], "title_case": ["title"], "sentence_case": ["text_format"],
 "sort_az": ["sort_by_alpha"], "sort_za": ["sort"], "paragraph": ["format_paragraph", "subject"],
 "stats": ["query_stats", "analytics"], "autocorrect": ["auto_fix_high"], "complete": ["autocomplete", "keyboard_tab"], "regex": ["regular_expression", "code"],
 "find": ["find_replace", "search"], "select_all": ["select_all"], "nav_pane": ["left_panel_open", "list_alt"], "focus": ["center_focus_strong"],
 "dark": ["dark_mode"], "zoom_in": ["zoom_in"], "zoom_out": ["zoom_out"], "collapse": ["expand_less"], "search": ["search"],
 "doc": ["description"], "sheet": ["table_chart"], "slides": ["slideshow"], "add_slide": ["add_box"], "delete": ["delete"], "play": ["play_arrow"],
 "import": ["upload_file", "download"],
}
out = ["// SPDX-License-Identifier: Apache-2.0", "// Generated by tools/gen_icons.py from Google Material Symbols (Outlined, 400, 24px). See THIRD_PARTY.md.",
       "pub const ICONS: &[(&str, &str)] = &["]
for ours, cands in ICONS.items():
    for n in cands:
        try:
            svg = urllib.request.urlopen(BASE % (n, n), timeout=30).read().decode()
        except Exception:
            continue
        d = " ".join(re.findall(r'<path d="([^"]+)"', svg))
        if d:
            out.append('    ("%s", "%s"),' % (ours, d)); print("ok  ", ours, "<-", n); break
    else:
        print("MISS", ours, cands, file=sys.stderr)
out.append("];")
open("crates/omni-shell/src/icons_data.rs", "w").write("\n".join(out) + "\n")
